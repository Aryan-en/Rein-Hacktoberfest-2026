function inside(x: number, y: number, poly: Poly): boolean {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]!;
    const [xj, yj] = poly[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

export const MAP_W = 1000;
export const MAP_H = 500;
const LAT_TOP = 84;
const LAT_BOTTOM = -58;

export const project = (lon: number, lat: number): [number, number] => [
  ((lon + 180) / 360) * MAP_W,
  ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * MAP_H,
];

let cached: string | null = null;
/** SVG path of tiny round dots covering the land masses. */
export function landDotsPath(): string {
  if (cached) return cached;
  const parts: string[] = [];
  const step = 2.2;
  for (let lat = LAT_TOP - 2; lat > LAT_BOTTOM; lat -= step) {
    for (let lon = -178; lon < 180; lon += step) {
      if (POLYS.some((p) => inside(lon, lat, p))) {
        const [x, y] = project(lon, lat);
        parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
      }
    }
  }
  cached = parts.join("");
  return cached;
}
